const M_PER_DEG_LAT = 111000;

function distanceM(a, b) {
  const R = 6371000;
  const toRad = (d) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return Math.round(2 * R * Math.asin(Math.sqrt(h)));
}

export function mockPlaces({ lat, lng, radius }) {
  const mPerDegLng = M_PER_DEG_LAT * Math.cos((lat * Math.PI) / 180);
  return RAW.map(([name, category, east, north, blogCount, permitDate, status], i) => {
    const p = { lat: lat + north / M_PER_DEG_LAT, lng: lng + east / mPerDegLng };
    return {
      id: `mock-${i}`,
      name,
      category,
      address: `서울 노원구 공릉로 ${100 + i * 7} (예시)`,
      jibun: '서울 노원구 공릉동 (예시)',
      phone: '',
      url: '',
      distance: distanceM({ lat, lng }, p),
      ...p,
      blogCount,
      license: { permitDate, status, closed: status === '폐업' },
    };
  })
    .filter((p) => p.distance <= radius)
    .sort((a, b) => a.distance - b.distance);
}
